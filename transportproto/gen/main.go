package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"runtime"
	"strconv"
)

const suiteVersion uint16 = 1

func main() {
	check := flag.Bool("check", false, "fail when generated files differ")
	flag.Parse()
	root := moduleRoot()
	catalog := schemaFingerprint(filepath.Join(root, "catalogproto", "messages_gen.go"))
	catalogWorker := schemaFingerprint(filepath.Join(root, "catalogworker", "messages_gen.go"))
	mount := schemaFingerprint(filepath.Join(root, "mountproto", "messages_gen.go"))
	sourceDriver := schemaFingerprint(filepath.Join(root, "sourcedriverproto", "messages_gen.go"))
	wireBuild := suiteWireBuild(catalog, catalogWorker, mount, sourceDriver)
	goSource, err := format.Source([]byte(fmt.Sprintf(`// Code generated by transportproto/gen; DO NOT EDIT.

package transportproto

const Version uint16 = %d
const WireBuild = %q
const CatalogSchemaFingerprint = %q
const CatalogWorkerSchemaFingerprint = %q
const MountSchemaFingerprint = %q
const SourceDriverSchemaFingerprint = %q
`, suiteVersion, wireBuild, catalog, catalogWorker, mount, sourceDriver)))
	if err != nil {
		panic(err)
	}
	swiftSource := []byte(fmt.Sprintf(`// Code generated by transportproto/gen; DO NOT EDIT.

public enum FuseKitTransportProtocol {
  public static let version: UInt16 = %d
  public static let wireBuild = %q
}
`, suiteVersion, wireBuild))
	outputs := map[string][]byte{
		filepath.Join(root, "transportproto", "identity_gen.go"):                                    goSource,
		filepath.Join(root, "Sources", "FuseKit", "Generated", "TransportProtocol.generated.swift"): swiftSource,
	}
	for path, source := range outputs {
		if *check {
			current, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(current, source) {
				fmt.Fprintf(os.Stderr, "%s is stale; run go generate ./transportproto\n", path)
				os.Exit(1)
			}
			continue
		}
		if err := os.WriteFile(path, source, 0o644); err != nil {
			panic(err)
		}
	}
}

func schemaFingerprint(path string) string {
	parsed, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		panic(fmt.Errorf("parse schema %s: %w", path, err))
	}
	for _, declaration := range parsed.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.CONST {
			continue
		}
		for _, specification := range general.Specs {
			value, ok := specification.(*ast.ValueSpec)
			if !ok || len(value.Names) != 1 || value.Names[0].Name != "SchemaFingerprint" || len(value.Values) != 1 {
				continue
			}
			literal, ok := value.Values[0].(*ast.BasicLit)
			if !ok || literal.Kind != token.STRING {
				panic(fmt.Errorf("schema fingerprint in %s is not a string literal", path))
			}
			fingerprint, err := strconv.Unquote(literal.Value)
			if err != nil {
				panic(fmt.Errorf("decode schema fingerprint in %s: %w", path, err))
			}
			return fingerprint
		}
	}
	panic(fmt.Errorf("schema fingerprint missing from %s", path))
}

func suiteWireBuild(catalog, catalogWorker, mount, sourceDriver string) string {
	raw := fmt.Sprintf(
		"version:%d\ncatalog:%s\ncatalog_worker:%s\nmount:%s\nsource_driver:%s\n",
		suiteVersion, catalog, catalogWorker, mount, sourceDriver,
	)
	digest := sha256.Sum256([]byte(raw))
	return "com.yasyf.fusekit.transport/" + hex.EncodeToString(digest[:]) + "/v1"
}

func moduleRoot() string {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		panic("transportproto/gen: caller path unavailable")
	}
	return filepath.Clean(filepath.Join(filepath.Dir(file), "..", ".."))
}
